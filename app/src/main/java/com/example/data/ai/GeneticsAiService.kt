import java.util.concurrent.TimeUnit

class GeneticsAiService {

    private val client = OkHttpClient.Builder()
        .connectTimeout(25, TimeUnit.SECONDS)
        .readTimeout(25, TimeUnit.SECONDS)
        .build()

    suspend fun generateResponse(
        prompt: String,
        language: AppLanguage,
        chatHistory: List<Pair<String, String>> = emptyList()
    ): Pair<String, Boolean> = withContext(Dispatchers.IO) {
        val apiKey = try {
            val field = BuildConfig::class.java.getField("GEMINI_API_KEY")
            field.get(null) as? String ?: ""
        } catch (e: Throwable) {
            ""
        }

        val hasValidKey = apiKey.isNotBlank() && !apiKey.contains("MY_GEMINI_API_KEY")

        if (hasValidKey) {
            try {
                val realResponse = callGeminiApi(prompt, apiKey, language, chatHistory)
                if (realResponse.isNotBlank()) {
                    return@withContext Pair(realResponse, true)
                }
            } catch (e: Exception) {
                // Gracefully fallback to the built-in intelligent biology engine with notification
                val fallback = generateEducationalEngineResponse(prompt, language)
                val note = if (language == AppLanguage.ARABIC) {
                    "⚠️ [وضع العرض التجريبي التعليمي]: تعذر الاتصال بـ Gemini (${e.localizedMessage ?: "شبكة"}). تم إنشاء الشرح عبر محرك GeneLab للوراثة:\n\n"
                } else {
                    "⚠️ [Educational Demo Mode]: Unable to reach Gemini (${e.localizedMessage ?: "network"}). Answer generated by GeneLab Biology Engine:\n\n"
                }
                return@withContext Pair(note + fallback, false)
            }
        }

        // Demo / Built-in Biology Engine Mode
        val fallback = generateEducationalEngineResponse(prompt, language)
        val note = if (language == AppLanguage.ARABIC) {
            "💡 [وضع المحرك التعليمي المدمج - GeneLab Engine]:\n"
        } else {
            "💡 [Built-in GeneLab Biology Engine - Educational Mode]:\n"
        }
        Pair(note + fallback, false)
    }

    private fun callGeminiApi(
        userPrompt: String,
        apiKey: String,
        language: AppLanguage,
        chatHistory: List<Pair<String, String>>
    ): String {
        val systemInstruction = if (language == AppLanguage.ARABIC) {
            "أنت المساعد الذكي المتخصص في علم الوراثة والبيولوجيا الجزيئية في تطبيق GeneLab AI. مهمتك هي شرح المفاهيم بوضوح علمي فائق، حل مسائل الوراثة المندلية خطوة بخطوة مع توضيح الطرز الجينية والمظهرية، حساب مربعات بانيت ونسب التوريث، وتقديم نصائح دراسية دقيقة مع الشكر والتشجيع باللغة العربية الفصحى."
        } else {
            "You are the specialized Genetics and Molecular Biology AI Assistant for GeneLab AI. Your task is to explain concepts with scientific clarity, solve Mendelian genetics problems step by step with genotypes and phenotypes, compute Punnett squares and inheritance ratios, and provide helpful educational guidance."
        }

        val url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=$apiKey"

        val contentsArray = JSONArray()

        // Include system prompt as first turn if needed or history
        for ((role, text) in chatHistory.takeLast(4)) {
            val contentObj = JSONObject()
            contentObj.put("role", if (role == "user") "user" else "model")
            val partsArray = JSONArray()
            val part = JSONObject().put("text", text)
            partsArray.put(part)
            contentObj.put("parts", partsArray)
            contentsArray.put(contentObj)
        }

        val currentTurn = JSONObject()
        currentTurn.put("role", "user")
        val currentParts = JSONArray()
        currentParts.put(JSONObject().put("text", "System Instruction: $systemInstruction\n\nUser Question: $userPrompt"))
        currentTurn.put("parts", currentParts)
        contentsArray.put(currentTurn)

        val rootJson = JSONObject()
        rootJson.put("contents", contentsArray)

        val body = rootJson.toString().toRequestBody("application/json; charset=utf-8".toMediaType())
        val request = Request.Builder()
            .url(url)
            .post(body)
            .build()

        client.newCall(request).execute().use { response ->
            if (!response.isSuccessful) {
                throw Exception("HTTP ${response.code}: ${response.message}")
            }
            val respBody = response.body?.string() ?: throw Exception("Empty response from AI server")
            val json = JSONObject(respBody)
            val candidates = json.optJSONArray("candidates")
            if (candidates != null && candidates.length() > 0) {
                val firstCandidate = candidates.getJSONObject(0)
                val content = firstCandidate.getJSONObject("content")
                val parts = content.getJSONArray("parts")
                if (parts.length() > 0) {
                    return parts.getJSONObject(0).getString("text")
                }
            }
            throw Exception("No text content returned from Gemini")
        }
    }

    fun generateEducationalEngineResponse(prompt: String, language: AppLanguage): String {
        val lower = prompt.lowercase()
        val isAr = language == AppLanguage.ARABIC

        // 1. Detect Monohybrid or Dihybrid Cross
        val crossRegex = Regex("([a-zA-Z]{2,4})\\s*[xX*×]\\s*([a-zA-Z]{2,4})")
        val match = crossRegex.find(prompt)
        if (match != null) {
            val p1 = match.groupValues[1]
            val p2 = match.groupValues[2]

            return if (p1.length == 2 && p2.length == 2) {
                val res = GeneticsEngine.calculateMonohybrid(p1, p2)
                if (isAr) {
                    "🧬 حل مسألة التزاوج الأحادي ($p1 × $p2):\n\n" +
                            res.explanationAr + "\n\n" +
                            "📊 مصفوفة مربع بانيت الناتجة:\n" +
                            "الأمشاج الأبوية: ${res.parent1Gametes.joinToString()} مع ${res.parent2Gametes.joinToString()}\n" +
                            "النسب المئوية:\n" +
                            res.genotypePercentages.entries.joinToString("\n") { "• الطراز ${it.key}: ${it.value.toInt()}%" } + "\n\n" +
                            "💡 قاعدة مندلية: تنفصل أليلات الجين الواحد في طور تكوين الأمشاج بصورة متكافئة ومستقلة."
                } else {
                    "🧬 Monohybrid Cross Solution ($p1 x $p2):\n\n" +
                            res.explanationEn + "\n\n" +
                            "📊 Punnett Square Outcome Matrix:\n" +
                            "Gametes: ${res.parent1Gametes.joinToString()} and ${res.parent2Gametes.joinToString()}\n" +
                            "Genotypic Frequencies:\n" +
                            res.genotypePercentages.entries.joinToString("\n") { "• Genotype ${it.key}: ${it.value.toInt()}%" } + "\n\n" +
                            "💡 Mendelian Principle: Mendel's First Law (Segregation) guarantees 50% probability for each parental allele in gamete distribution."
                }
            } else {
                val res = GeneticsEngine.calculateDihybrid(p1, p2)
                if (isAr) {
                    "🧬 حل مسألة التزاوج الثنائي الهجين ($p1 × $p2):\n\n" +
                            res.explanationAr + "\n\n" +
                            "النسب المظهرية للأبناء في مصفوفة الـ 16 خلية:\n" +
                            res.phenotypePercentages.entries.joinToString("\n") { "• ${it.key}: ${it.value}%" }
                } else {
                    "🧬 Dihybrid Cross Solution ($p1 x $p2):\n\n" +
                            res.explanationEn + "\n\n" +
                            "Phenotypic Distribution across 16 grid squares:\n" +
                            res.phenotypePercentages.entries.joinToString("\n") { "• ${it.key}: ${it.value}%" }
                }
            }
        }

        // 2. DNA / RNA / Transcription question
        if (lower.contains("dna") || lower.contains("rna") || lower.contains("حمض نووي") || lower.contains("قواعد")) {
            return if (isAr) {
                "🧬 الحمض النووي (DNA) والنسخ الحيوي:\n\n" +
                        "1. يتكون الـ DNA من سلسلتين متعاكستين بشكل لولب مزدوج تلتفان حول بعضهما.\n" +
                        "2. القواعد النيتروجينية وقواعد التكامل (تشارغاف):\n" +
                        "   • الأدينين (A) يرتبط دائماً مع الثايمين (T) برابطتين هيدروجينيتين.\n" +
                        "   • السيتوسين (C) يرتبط دائماً مع الجوانين (G) بثلاث روابط هيدروجينية.\n" +
                        "3. في الـ RNA، يحل اليوراسيل (U) محل الثايمين (T).\n" +
                        "4. الترجمة تتم عبر قراءة كودونات ثلاثية، تبدأ دائماً بكودون البدء AUG (ميثيونين)."
            } else {
                "🧬 DNA Architecture & Molecular Transcription:\n\n" +
                        "1. DNA consists of two antiparallel polynucleotide strands coiling in a double helix.\n" +
                        "2. Chargaff's Complementary Base Pairing:\n" +
                        "   • Adenine (A) binds exclusively with Thymine (T) via 2 hydrogen bonds.\n" +
                        "   • Guanine (G) binds exclusively with Cytosine (C) via 3 hydrogen bonds.\n" +
                        "3. In messenger RNA (mRNA), Uracil (U) substitutes for Thymine.\n" +
                        "4. Translation reads triplet codons starting at AUG (Methionine) to build polypeptide chains."
            }
        }

        // 3. Mitosis vs Meiosis
        if (lower.contains("mitosis") || lower.contains("meiosis") || lower.contains("انقسام")) {
            return if (isAr) {
                "🔬 مقارنة علمية: الانقسام المتساوي (Mitosis) مقابل الانقسام المنصف (Meiosis):\n\n" +
                        "• الانقسام المتساوي (الجسدي):\n" +
                        "  - يحدث في الخلايا الجسدية بهدف النمو وتعويض الخلايا التالفة.\n" +
                        "  - انقسام واحد ينتج خليتين ابنتين متطابقتين وراثياً ثنائية المجموعة الكروموسومية (2n).\n\n" +
                        "• الانقسام المنصف (الاختزالي):\n" +
                        "  - يحدث في الخلايا التناسلية لإنتاج الأمشاج (الحيوانات المنوية والبويضات).\n" +
                        "  - انقسامان متتاليان ينتجان 4 خلايا متنوعة وراثياً وأحادية المجموعة (n).\n" +
                        "  - يحدث خلاله العبور الجيني (Crossing Over) في الطور التمهيدي الأول مما يولد التنوع الوراثي."
            } else {
                "🔬 Scientific Comparison: Mitosis vs Meiosis:\n\n" +
                        "• Mitosis (Somatic Division):\n" +
                        "  - Occurs in body tissues for growth, development, and cellular regeneration.\n" +
                        "  - Single division cycle generating 2 genetically identical diploid (2n) daughter cells.\n\n" +
                        "• Meiosis (Reductional Division):\n" +
                        "  - Occurs in germline tissues to produce haploid (n) gametes (sperm and ova).\n" +
                        "  - Two successive divisions yielding 4 genetically unique haploid gametes.\n" +
                        "  - Crossing over in Prophase I exchanges non-sister chromatid segments to drive genetic diversity."
            }
        }

        // 4. Blood types / Codominance
        if (lower.contains("blood") || lower.contains("دم") || lower.contains("فصائل")) {
            return if (isAr) {
                "🩸 وراثة فصائل الدم البشرية (نظام ABO):\n\n" +
                        "1. يتحكم في فصائل الدم جين ذو ثلاثة أليلات بديلة: I^A و I^B و i.\n" +
                        "2. الأليلان I^A و I^B كلاهما سائدان سيادة مشتركة (Codominance) على الأليل المتنحي i.\n" +
                        "3. الطرز الجينية والمظهرية:\n" +
                        "   • فصيلة A: إما نقي (I^A I^A) أو هجين (I^A i)\n" +
                        "   • فصيلة B: إما نقي (I^B I^B) أو هجين (I^B i)\n" +
                        "   • فصيلة AB: طراز جيني واحد سائد مشترك (I^A I^B)\n" +
                        "   • فصيلة O: طراز جيني متنحٍ نقي فقط (ii)"
            } else {
                "🩸 Human ABO Blood Group Inheritance:\n\n" +
                        "1. Governed by multiple alleles: I^A, I^B, and recessive i.\n" +
                        "2. I^A and I^B exhibit codominance with each other, while both dominate over allele i.\n" +
                        "3. Genotype-to-Phenotype Mapping:\n" +
                        "   • Blood Type A: Homozygous (I^A I^A) or Heterozygous (I^A i)\n" +
                        "   • Blood Type B: Homozygous (I^B I^B) or Heterozygous (I^B i)\n" +
                        "   • Blood Type AB: Codominant heterozygote (I^A I^B) expressing both antigens\n" +
                        "   • Blood Type O: Homozygous recessive (ii)"
            }
        }

        // 5. Default comprehensive genetics response
        return if (isAr) {
            "🧬 مرحباً بك في مختبر GeneLab AI للوراثة!\n\n" +
                    "بصفتي مساعدك المتخصص في علم الوراثة، يمكنني مساعدتك في:\n" +
                    "• حل مسائل التزاوج المندلي وحساب احتمالات بانيت (مثال: اكتب 'Aa x Aa' أو 'Pp x pp').\n" +
                    "• تحليل تسلسلات الـ DNA وترجمتها إلى سلاسل أحماض أمينية.\n" +
                    "• توضيح آليات الطفرات الجينية (الاستبدال، الإزاحة، الطفرات الصامتة والمؤثرة).\n" +
                    "• تفسير أنماط الوراثة اللا مندلية (السيادة المشتركة، غير التامة، الصفات المرتبطة بالجنس).\n" +
                    "• الاستعداد للاختبارات والمساعدة في الواجبات المدرسية والجامعية.\n\n" +
                    "اطرح سؤالك أو أدخل الطرز الجينية للبدء فوراً!"
        } else {
            "🧬 Welcome to GeneLab AI Genetics Laboratory!\n\n" +
                    "As your dedicated biology specialist, I am equipped to assist you with:\n" +
                    "• Solving Mendelian inheritance problems and calculating Punnett squares (try typing 'Aa x Aa' or 'Bb x bb').\n" +
                    "• Transcribing and translating nucleotide sequences into polypeptide chains.\n" +
                    "• Demonstrating point mutations and frameshift alterations.\n" +
                    "• Explaining complex inheritance patterns (codominance, incomplete dominance, sex-linkage).\n" +
                    "• Quiz preparation and homework assistance.\n\n" +
                    "Ask any question or specify parental genotypes to begin!"
        }
    }
}
